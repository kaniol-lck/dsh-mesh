#!/usr/bin/env node
/**
 * init-project.mjs — scaffold a collaborating workspace (worklog + AGENTS charter).
 *
 * Creates an idempotent skeleton in an existing git repository:
 *   .worklog/todo/<role>.md, WORKLOG.md, dispatch/queue.md, gates.json, ops/
 *   .worklog/bin/{roadmap,defects,dispatch}.mjs  (thin forwarders)
 *   AGENTS.md  (rendered from docs/agents-template.md)
 *   .gitignore gets ".worklog/" once
 *
 * Usage:
 *   node scripts/init-project.mjs --dir <path> --name <project> [--roles a,b,c]
 *        [--dispatch-url http://127.0.0.1:8795] [--dry-run] [--force]
 *
 * Existing files are skipped unless --force. Exit codes: 0 ok, 2 bad args/target.
 */

import { existsSync, mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const HERE = path.dirname(fileURLToPath(import.meta.url))
const TEMPLATE = path.resolve(HERE, '..', 'docs', 'agents-template.md')
const USAGE = `init-project — scaffold a collaborating workspace

Usage:
  node scripts/init-project.mjs --dir <path> --name <project> [options]

Options:
  --dir <path>          target project root (must already be a git repository)
  --name <project>      project name written into AGENTS.md
  --roles <a,b,c>       session roles (default: main,docs)
  --dispatch-url <url>  local waker URL noted in the dispatch wrapper (default http://127.0.0.1:8795)
  --dry-run             print the plan, write nothing
  --force               overwrite existing files
  -h, --help            show this help

Exit codes: 0 ok, 2 bad arguments or target directory.`

function fail(message) {
  console.error(message)
  process.exit(2)
}

function parseArgs(argv) {
  const options = {
    dir: null,
    name: null,
    roles: 'main,docs',
    dispatchUrl: 'http://127.0.0.1:8795',
    dryRun: false,
    force: false,
  }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    const value = () => {
      const next = argv[index + 1]
      if (next === undefined) fail(`${arg} requires a value\n\n${USAGE}`)
      index += 1
      return next
    }
    switch (arg) {
      case '--dir': options.dir = value(); break
      case '--name': options.name = value(); break
      case '--roles': options.roles = value(); break
      case '--dispatch-url': options.dispatchUrl = value(); break
      case '--dry-run': options.dryRun = true; break
      case '--force': options.force = true; break
      case '-h':
      case '--help':
        console.log(USAGE)
        process.exit(0)
        break
      default:
        fail(`unknown argument: ${arg}\n\n${USAGE}`)
    }
  }
  if (!options.dir) fail(`--dir is required\n\n${USAGE}`)
  if (!options.name) fail(`--name is required\n\n${USAGE}`)
  options.roles = options.roles.split(',').map((role) => role.trim()).filter(Boolean)
  if (!options.roles.length) fail('--roles must list at least one role')
  return options
}

function forwarder(kind, candidates, extraNote) {
  const implName = kind === 'dispatch' ? 'mesh-dispatch.mjs' : `${kind}.mjs`
  return `#!/usr/bin/env node
/** Thin forwarder generated by init-project.mjs. ${extraNote} */
import { spawnSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import process from 'node:process'

const here = path.dirname(fileURLToPath(import.meta.url))
const candidates = [
  ${candidates.map((candidate) => candidate).join(',\n  ')},
].filter(Boolean)
const impl = candidates.find((candidate) => existsSync(candidate))
if (!impl) {
  console.error('${implName} not found. Install the worklog skill or set the matching environment variable.')
  console.error('looked in:')
  for (const candidate of candidates) console.error('  - ' + candidate)
  process.exit(1)
}
const result = spawnSync(process.execPath, [impl, ...process.argv.slice(2)], { stdio: 'inherit' })
process.exit(result.status ?? 1)
`
}

function todoFile(role) {
  return `<!-- session: ${role} · updated: ${new Date().toISOString().slice(0, 10)} -->
<!-- 格式（一行一条）：
- [P1] 标题 —— 说明；验收：可核对的完成标准；状态：未开始|进行中|已完成；归属：${role}；功能：标签
进行中必须带「归属」和 14 天内的「进展：YYYY-MM-DD」，否则按待办处理。 -->
<!-- 示例（可删）：
- [P1] 示例任务 —— 只改某目录；验收：测试通过；状态：未开始；归属：${role}；功能：示例 -->
`
}

function worklogFile(name) {
  return `# ${name} 工作日志

> 叙事与决策写这里；逐条任务放 \`todo/<角色>.md\`，总览由 \`node .worklog/bin/roadmap.mjs --write\` 生成。

## 格式示例

- 2026-01-01 决定：先做 A 再做 B，因为 B 依赖 A 的接口（\`DECISION: 先 A 后 B · owner · 2026-01-01 · 影响 todo 排序\`）。
- 缺陷回流：\`DEFECT: <签名> · <域> · <证据> · <blocking:no>\`。
`
}

function queueFile() {
  return `# 派活账本（协调会话维护）

| 编号 | 会话 | 任务 | 派出时间 | 期望产物 | 状态 |
|---|---|---|---|---|---|
| T-001 | <角色> | 示例 | 2026-01-01 | 文件/测试 | dispatched |
`
}

function gatesFile() {
  return `{
  "_comment": "空 gates 数组。关口用 match 胶囊清单（标题子串），不要用 feature 判据：新增同功能条目会让已绿关口回退。示例：id=G1、name=首个能力闭环、question=…、requires=[{match: 某待办标题片段}]",
  "gates": []
}
`
}

function ensureGitignore(root, log) {
  const file = path.join(root, '.gitignore')
  const line = '.worklog/'
  if (!existsSync(file)) {
    writeFileSync(file, `${line}\n`, 'utf8')
    log('created', '.gitignore')
    return
  }
  const content = readFileSync(file, 'utf8')
  const lines = content.split(/\r?\n/).map((entry) => entry.trim())
  if (lines.includes(line)) {
    log('skipped', '.gitignore (.worklog/ already ignored)')
    return
  }
  const next = content.endsWith('\n') || content === '' ? `${content}${line}\n` : `${content}\n${line}\n`
  writeFileSync(file, next, 'utf8')
  log('updated', '.gitignore (+ .worklog/)')
}

function renderAgents(name, roles) {
  if (!existsSync(TEMPLATE)) fail(`charter template not found: ${TEMPLATE}`)
  return readFileSync(TEMPLATE, 'utf8')
    .replaceAll('<项目名>', name)
    .replaceAll('<角色列表>', roles.join(' / '))
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  const root = path.resolve(options.dir)
  if (!existsSync(root) || !statSync(root).isDirectory()) fail(`target is not a directory: ${root}`)
  if (!existsSync(path.join(root, '.git')) && !options.force) {
    fail(`not a git repository: ${root}\nrun "git init" there first, or pass --force to scaffold anyway`)
  }
  const roles = options.roles
  const worklog = path.join(root, '.worklog')
  const plan = []

  const plannedFiles = [
    [path.join(worklog, 'WORKLOG.md'), () => worklogFile(options.name)],
    [path.join(worklog, 'dispatch', 'queue.md'), queueFile],
    [path.join(worklog, 'gates.json'), gatesFile],
    [path.join(root, 'AGENTS.md'), () => renderAgents(options.name, roles)],
    [
      path.join(worklog, 'bin', 'roadmap.mjs'),
      () =>
        forwarder(
          'roadmap',
          [
            'process.env.WORKLOG_SCRIPTS',
            "path.resolve(here, '..', '..', '..', 'skills', 'worklog', 'scripts')",
            "path.join(process.env.HOME || process.env.USERPROFILE || '', '.dsh', 'skills', 'worklog', 'scripts')",
          ],
          'Set WORKLOG_SCRIPTS to the skill scripts directory to override.',
        ),
    ],
    [
      path.join(worklog, 'bin', 'defects.mjs'),
      () =>
        forwarder(
          'defects',
          [
            'process.env.WORKLOG_SCRIPTS',
            "path.resolve(here, '..', '..', '..', 'skills', 'worklog', 'scripts')",
            "path.join(process.env.HOME || process.env.USERPROFILE || '', '.dsh', 'skills', 'worklog', 'scripts')",
          ],
          'Set WORKLOG_SCRIPTS to the skill scripts directory to override.',
        ),
    ],
    [
      path.join(worklog, 'bin', 'dispatch.mjs'),
      () =>
        forwarder(
          'dispatch',
          [
            'process.env.MESH_DISPATCH_SCRIPT',
            "path.resolve(here, '..', '..', '..', 'scripts', 'mesh-dispatch.mjs')",
            "path.join(process.env.HOME || process.env.USERPROFILE || '', '.dsh', 'skills', 'mesh', 'scripts', 'mesh-dispatch.mjs')",
          ],
          `Optional local helper. Waker URL: ${options.dispatchUrl} (MESH_WAKER_URL).`,
        ),
    ],
  ]
  for (const role of roles) plannedFiles.push([path.join(worklog, 'todo', `${role}.md`), () => todoFile(role)])

  const dirs = [worklog, path.join(worklog, 'todo'), path.join(worklog, 'dispatch'), path.join(worklog, 'ops'), path.join(worklog, 'bin')]
  const actions = []
  for (const dir of dirs) actions.push({ kind: 'dir', path: dir })
  for (const [file, render] of plannedFiles) actions.push({ kind: 'file', path: file, render })
  actions.push({ kind: 'gitignore', path: path.join(root, '.gitignore') })

  if (options.dryRun) {
    console.log(`DRY RUN: ${root}`)
    for (const action of actions) console.log(`  plan ${action.kind} ${path.relative(root, action.path)}`)
    return
  }

  const counts = { created: 0, skipped: 0, updated: 0 }
  const log = (status, label) => {
    counts[status] += 1
    console.log(`  ${status.padEnd(7)} ${label}`)
  }
  for (const action of actions) {
    if (action.kind === 'dir') {
      if (existsSync(action.path)) log('skipped', `${path.relative(root, action.path)}/`)
      else {
        mkdirSync(action.path, { recursive: true })
        log('created', `${path.relative(root, action.path)}/`)
      }
      continue
    }
    if (action.kind === 'gitignore') {
      ensureGitignore(root, log)
      continue
    }
    const rel = path.relative(root, action.path)
    const exists = existsSync(action.path)
    if (exists && !options.force) {
      log('skipped', rel)
      continue
    }
    mkdirSync(path.dirname(action.path), { recursive: true })
    writeFileSync(action.path, action.render(), 'utf8')
    log(exists ? 'updated' : 'created', rel)
  }
  console.log(`done: ${counts.created} created, ${counts.updated} updated, ${counts.skipped} skipped`)
}

main()
