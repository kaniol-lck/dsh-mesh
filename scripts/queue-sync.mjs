#!/usr/bin/env node
/**
 * queue-sync.mjs — shard the dispatch ledger by originating session, generate the aggregate view.
 *
 * Shards:  .worklog/dispatch/queue/<sessionId>.md   (one row per dispatch, hand/script written)
 * Aggregate: .worklog/dispatch/queue.md             (GENERATED — never hand-edited)
 *
 * The aggregate is the human page and is also what check-ledger reads; rows keep the
 * classic format "| T-123 | role | subject | time | expect | status |".
 *
 * Usage:
 *   node scripts/queue-sync.mjs --sync                 regenerate the aggregate
 *   node scripts/queue-sync.mjs --check                exit 1 if the aggregate is stale
 *   node scripts/queue-sync.mjs --session <id> --row "| T-1 | docs | ... |"
 *   node scripts/queue-sync.mjs --migrate [--apply]    move the old monolithic queue.md into _legacy.md
 *
 * Migration writes only with --apply (dry-run otherwise) and must preserve the row count.
 * Exit codes: 0 ok, 1 drift/error, 2 usage error.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import process from 'node:process'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const WORKLOG = process.env.MESH_WORKLOG_DIR ?? path.join(ROOT, '.worklog')
const QUEUE_DIR = path.join(WORKLOG, 'dispatch', 'queue')
const AGGREGATE = path.join(WORKLOG, 'dispatch', 'queue.md')
const LEGACY_SHARD = '_legacy.md'
const ROW = /^\|\s*[A-Za-z0-9]/
const PREAMBLE = [
  '<!-- generated by scripts/queue-sync.mjs — do not hand-edit;',
  '     add rows to .worklog/dispatch/queue/<sessionId>.md and run --sync -->',
  '',
  '# 派活账本（聚合视图，自动生成）',
  '',
  '来源：`.worklog/dispatch/queue/<发起会话>.md`（按发起会话分片，并发写不互相覆盖）。',
  '',
  '| 单号 | 归属 | 任务 | 派出时间 | 期望产物 | 状态 |',
  '|---|---|---|---|---|---|',
]
const USAGE = `queue-sync.mjs — sharded dispatch ledger + generated aggregate

Usage:
  node queue-sync.mjs --sync                  regenerate dispatch/queue.md from the shards
  node queue-sync.mjs --check                 exit 1 when the aggregate is stale (drift)
  node queue-sync.mjs --session <id> --row "| T-1 | docs | ... |"
  node queue-sync.mjs --migrate [--apply]     move the monolithic queue.md into _legacy.md

Layout: dispatch/queue/<sessionId>.md is the write target per originating session;
dispatch/queue.md is generated and must never be edited by hand. --migrate defaults to
dry-run; --apply is explicit. Exit codes: 0 ok, 1 drift/error, 2 usage error.`

function parseArgs(argv) {
  const options = { sync: false, check: false, migrate: false, apply: false, session: null, row: null, json: false }
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index]
    const value = () => {
      const next = argv[index + 1]
      if (next === undefined) {
        console.error(`${arg} requires a value\n\n${USAGE}`)
        process.exit(2)
      }
      index += 1
      return next
    }
    if (arg === '--sync') options.sync = true
    else if (arg === '--check') options.check = true
    else if (arg === '--migrate') options.migrate = true
    else if (arg === '--apply') options.apply = true
    else if (arg === '--json') options.json = true
    else if (arg === '--session') options.session = value()
    else if (arg === '--row') options.row = value()
    else if (arg === '-h' || arg === '--help') {
      console.log(USAGE)
      process.exit(0)
    } else {
      console.error(`unknown argument: ${arg}\n\n${USAGE}`)
      process.exit(2)
    }
  }
  return options
}

function safeSessionId(value) {
  if (!/^[A-Za-z0-9._-]+$/.test(String(value))) throw new Error(`invalid session id: ${value}`)
  return String(value)
}

function tableRowsOf(text) {
  return text.split(/\r?\n/).filter((line) => ROW.test(line))
}

function readShards() {
  if (!existsSync(QUEUE_DIR)) return []
  const names = readdirSync(QUEUE_DIR).filter((name) => name.endsWith('.md'))
  names.sort((left, right) => {
    if (left === LEGACY_SHARD) return -1
    if (right === LEGACY_SHARD) return 1
    return left.localeCompare(right)
  })
  return names.map((name) => ({
    file: path.join(QUEUE_DIR, name),
    name,
    rows: tableRowsOf(readFileSync(path.join(QUEUE_DIR, name), 'utf8')),
  }))
}

function render(shards) {
  const rows = shards.flatMap((shard) => shard.rows)
  return [...PREAMBLE, ...rows, ''].join('\n')
}

function writeAggregate(shards) {
  mkdirSync(path.dirname(AGGREGATE), { recursive: true })
  writeFileSync(AGGREGATE, render(shards), 'utf8')
}

function appendRow(session, row) {
  if (!ROW.test(row)) throw new Error('--row must be a markdown table row starting with "| "')
  mkdirSync(QUEUE_DIR, { recursive: true })
  const file = path.join(QUEUE_DIR, `${safeSessionId(session)}.md`)
  const header = `<!-- shard for session ${session}; one markdown table row per dispatch -->\n`
  const existing = existsSync(file) ? readFileSync(file, 'utf8') : header
  const body = existing.endsWith('\n') ? existing : existing + '\n'
  writeFileSync(file, body + row.trim() + '\n', 'utf8')
  writeAggregate(readShards())
}

function migrate(apply) {
  if (!existsSync(AGGREGATE)) throw new Error(`missing ${AGGREGATE}`)
  const oldRows = tableRowsOf(readFileSync(AGGREGATE, 'utf8'))
  mkdirSync(QUEUE_DIR, { recursive: true })
  const shardFile = path.join(QUEUE_DIR, LEGACY_SHARD)
  if (apply) {
    const header = '<!-- migrated from the pre-sharding dispatch/queue.md (origin unknown; kept verbatim) -->\n'
    writeFileSync(shardFile, [header, ...oldRows, ''].join('\n'), 'utf8')
    writeAggregate(readShards())
  }
  const newCount = apply ? tableRowsOf(readFileSync(AGGREGATE, 'utf8')).length : oldRows.length
  return { apply, oldRowCount: oldRows.length, newRowCount: newCount, shardFile }
}

function main() {
  const options = parseArgs(process.argv.slice(2))
  if (options.migrate) {
    const result = migrate(options.apply)
    console.log(
      `migrate: ${result.oldRowCount} rows -> ${result.shardFile} (${result.apply ? 'APPLIED' : 'dry-run, use --apply'})` +
        `; aggregate rows ${result.newRowCount}`,
    )
    if (result.oldRowCount !== result.newRowCount) {
      console.error('MIGRATION MISMATCH: row count changed')
      process.exit(1)
    }
    return
  }
  if (options.session !== null || options.row !== null) {
    if (!options.session || options.row === null) {
      console.error(`--session and --row must be used together\n\n${USAGE}`)
      process.exit(2)
    }
    appendRow(options.session, options.row)
    console.log(`appended to dispatch/queue/${safeSessionId(options.session)}.md and regenerated queue.md`)
    return
  }
  if (options.check) {
    const expected = render(readShards())
    const actual = existsSync(AGGREGATE) ? readFileSync(AGGREGATE, 'utf8') : ''
    const ok = expected === actual
    if (options.json) console.log(JSON.stringify({ aggregate: AGGREGATE, rowCount: tableRowsOf(expected).length, ok }, null, 2))
    else console.log(ok ? `ok queue.md matches ${tableRowsOf(expected).length} shard rows` : 'FAIL queue.md is stale: run node scripts/queue-sync.mjs --sync')
    process.exit(ok ? 0 : 1)
  }
  // default / --sync
  writeAggregate(readShards())
  const count = tableRowsOf(readFileSync(AGGREGATE, 'utf8')).length
  if (options.json) console.log(JSON.stringify({ aggregate: AGGREGATE, rowCount: count }, null, 2))
  else console.log(`queue.md regenerated from shards: ${count} rows`)
}

try {
  main()
} catch (error) {
  console.error(`ERROR ${error.message}`)
  process.exit(1)
}
